"""
Pull the latin subset of our three families out of the Google Fonts CSS, download
the woff2 files into client/public/fonts/, and emit a local @font-face sheet.

Why: docs/DESIGN.md step 6. The app runs on a self-hosted LAN box under a strict
CSP (`style-src 'self'`), so a remote stylesheet is both blocked and a third-party
dependency on every page load. Fonts must ship with the app.
"""

import os
import re
import urllib.request

CSS_IN = "tmp/gfonts.css"
OUT_DIR = "client/public/fonts"
OUT_CSS = "client/src/fonts.css"

# The latin subset is the one carrying U+0000-00FF. Everything else is Cyrillic,
# Greek, Vietnamese etc. and would triple the payload for no benefit here.
LATIN = "U+0000-00FF"
LATIN_EXT = "U+0100-02BA"

KEEP_RANGES = {LATIN, LATIN_EXT}

UA = (
    "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0 Safari/537.36"
)


def main():
    css = open(CSS_IN, encoding="utf-8").read()
    blocks = re.findall(r"@font-face\s*\{(.*?)\}", css, re.S)

    os.makedirs(OUT_DIR, exist_ok=True)

    out = []
    downloaded = []

    for block in blocks:
        rng_match = re.search(r"unicode-range:\s*([^;]+);", block)
        if not rng_match:
            continue
        # Google emits a full comma list per subset, e.g.
        #   U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, ...
        # The subset is identified by its FIRST entry, not by equality with the
        # whole list — an equality check here silently matches nothing.
        first = rng_match.group(1).strip().split(",")[0].strip()
        if first not in KEEP_RANGES:
            continue

        family = re.search(r"font-family:\s*'([^']+)'", block).group(1)
        weight = re.search(r"font-weight:\s*([0-9 ]+);", block).group(1).strip()
        style = re.search(r"font-style:\s*(\w+);", block)
        style = style.group(1) if style else "normal"
        url = re.search(r"src:\s*url\(([^)]+)\)", block).group(1)

        slug = family.lower().replace(" ", "-")
        style_slug = "" if style == "normal" else f"-{style}"
        weight_slug = weight.replace(" ", "-")
        name = f"{slug}-{weight_slug}{style_slug}-{first[2:].lower()}.woff2"

        req = urllib.request.Request(url, headers={"User-Agent": UA})
        with urllib.request.urlopen(req, timeout=30) as r:
            data = r.read()

        with open(os.path.join(OUT_DIR, name), "wb") as fh:
            fh.write(data)
        downloaded.append((name, len(data)))

        out.append(
            "@font-face {\n"
            f"  font-family: '{family}';\n"
            f"  font-style: {style};\n"
            f"  font-weight: {weight};\n"
            "  font-display: swap;\n"
            f"  src: url('/fonts/{name}') format('woff2');\n"
            f"  unicode-range: {rng_match.group(1).strip()};\n"
            "}"
        )

    header = (
        "/**\n"
        " * Self-hosted webfonts. Generated by tools/fetch-fonts.py.\n"
        " *\n"
        " * Do NOT replace these with a <link> to fonts.googleapis.com: the app ships\n"
        " * `style-src 'self'` in its CSP, so a remote stylesheet is blocked outright,\n"
        " * and it would put a third party in the critical path of every page load.\n"
        " */\n\n"
    )

    with open(OUT_CSS, "w", encoding="utf-8") as fh:
        fh.write(header + "\n\n".join(out) + "\n")

    total = sum(size for _, size in downloaded)
    print(f"downloaded {len(downloaded)} files, {total / 1024:.1f} KB total")
    for name, size in downloaded:
        print(f"  {name}  {size / 1024:.1f} KB")
    print(f"\nwrote {OUT_CSS}")


if __name__ == "__main__":
    main()